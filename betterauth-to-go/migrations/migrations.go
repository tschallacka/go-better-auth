// Package migrations ships the PostgreSQL DDL of the tables better-auth
// 1.6.14 uses, exactly as the library's own migrator writes it, for projects
// that do not have the tables yet. The module never applies them itself:
// hand them to goose, migrate, atlas or psql, or skip them if the tables
// already exist (pgstore.CheckSchema tells you which).
//
// Files, applied in order, each only adding what the earlier ones lack:
//
//	0001_core.sql          user, session, account, verification
//	0002_organization.sql  organization, member, invitation, session.activeOrganizationId
//	0003_two_factor.sql    twoFactor, user.twoFactorEnabled
//	0004_passkey.sql       passkey
//
// They are generated by testdata/gen/schema.mjs; do not edit them by hand.
package migrations

import (
	"embed"
	"io/fs"
	"sort"
)

//go:embed *.sql
var files embed.FS

// FS holds the migration files at its root.
var FS fs.FS = files

// Names returns the migration file names in the order they apply.
func Names() []string {
	entries, _ := fs.ReadDir(files, ".")
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	return names
}

// Read returns one migration's SQL.
func Read(name string) (string, error) {
	b, err := fs.ReadFile(files, name)
	return string(b), err
}
