// Package testvectors loads the fixtures recorded from the real better-auth
// by testdata/gen. Test code only.
package testvectors

import (
	"encoding/json"
	"os"
	"path/filepath"
	"runtime"
	"testing"
)

// Crypto is testdata/fixtures/crypto-vectors.json.
type Crypto struct {
	Generator      string `json:"generator"`
	PasswordHashes []struct {
		Password string `json:"password"`
		Hash     string `json:"hash"`
	} `json:"passwordHashes"`
	PasswordChecks []struct {
		Hash     string `json:"hash"`
		Password string `json:"password"`
		OK       bool   `json:"ok"`
	} `json:"passwordChecks"`
	Symmetric []struct {
		Secret     string `json:"secret"`
		Plaintext  string `json:"plaintext"`
		Ciphertext string `json:"ciphertext"`
	} `json:"symmetric"`
	SymmetricVersioned []struct {
		Keys           map[string]string `json:"keys"`
		CurrentVersion int64             `json:"currentVersion"`
		LegacySecret   string            `json:"legacySecret"`
		Plaintext      string            `json:"plaintext"`
		Ciphertext     string            `json:"ciphertext"`
		Decrypted      string            `json:"decrypted"`
	} `json:"symmetricVersioned"`
	Signatures []struct {
		Secret    string `json:"secret"`
		Value     string `json:"value"`
		Signature string `json:"signature"`
	} `json:"signatures"`
	SignedCookieHeaders []struct {
		Name    string `json:"name"`
		Value   string `json:"value"`
		Secret  string `json:"secret"`
		Options struct {
			Prefix      string `json:"prefix"`
			Path        string `json:"path"`
			Domain      string `json:"domain"`
			HTTPOnly    bool   `json:"httpOnly"`
			Secure      bool   `json:"secure"`
			SameSite    string `json:"sameSite"`
			MaxAge      *int   `json:"maxAge"`
			Partitioned bool   `json:"partitioned"`
		} `json:"options"`
		Header string `json:"header"`
	} `json:"signedCookieHeaders"`
	SignedCookieReads []struct {
		Label  string          `json:"label"`
		Cookie string          `json:"cookie"`
		Name   string          `json:"name"`
		Secret string          `json:"secret"`
		Result json.RawMessage `json:"result"` // a string, false or null
	} `json:"signedCookieReads"`
	ConstantTimeEqual []struct {
		A     string `json:"a"`
		B     string `json:"b"`
		Equal bool   `json:"equal"`
	} `json:"constantTimeEqual"`
	Builtins Builtins `json:"builtins"`
}

// Builtins are JavaScript built-in results recorded from Node.
type Builtins struct {
	EncodeURIComponent []struct {
		In  string `json:"in"`
		Out string `json:"out"`
	} `json:"encodeURIComponent"`
	DecodeURIComponent []struct {
		In    string `json:"in"`
		Value string `json:"value"`
		Error string `json:"error"`
	} `json:"decodeURIComponent"`
	Atob []struct {
		In    string `json:"in"`
		Hex   string `json:"hex"`
		Error string `json:"error"`
	} `json:"atob"`
	ParseInt []struct {
		In  string  `json:"in"`
		Out *string `json:"out"` // nil for NaN
	} `json:"parseInt"`
	Trim []struct {
		In  string `json:"in"`
		Out string `json:"out"`
	} `json:"trim"`
	TextDecoder []struct {
		Hex string `json:"hex"`
		Out string `json:"out"`
	} `json:"textDecoder"`
	ToLowerCase []struct {
		In  string `json:"in"`
		Out string `json:"out"`
	} `json:"toLowerCase"`
}

// FixturesDir is the absolute path of testdata/fixtures.
func FixturesDir() string {
	_, file, _, _ := runtime.Caller(0)
	return filepath.Join(filepath.Dir(file), "..", "..", "testdata", "fixtures")
}

// GenDir is the absolute path of testdata/gen.
func GenDir() string {
	return filepath.Join(FixturesDir(), "..", "gen")
}

// LoadCrypto reads the crypto vectors or fails the test.
func LoadCrypto(t testing.TB) *Crypto {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(FixturesDir(), "crypto-vectors.json"))
	if err != nil {
		t.Fatalf("reading crypto vectors: %v", err)
	}
	var v Crypto
	if err := json.Unmarshal(raw, &v); err != nil {
		t.Fatalf("parsing crypto vectors: %v", err)
	}
	if v.Generator != "better-auth 1.6.14" {
		t.Fatalf("vectors were generated by %q, want better-auth 1.6.14", v.Generator)
	}
	return &v
}
